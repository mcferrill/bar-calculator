// Run against a migrated local dev server. Use PLAYWRIGHT_MODULE for an existing global install.
import assert from "node:assert/strict";
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || "playwright");
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || "/usr/lib/chromium/chromium", headless: true });
const page = await browser.newPage({ viewport: { width: 390, height: 844 } });
const base = process.env.BASE_URL || "http://localhost:4322";
const errors = [];
page.on("pageerror", (error) => errors.push(error.message));
page.on("dialog", (dialog) => dialog.accept());
let id;
try {
	await page.goto(base);
	assert.equal(await page.locator("select[name=unit]").count(), 0);
	await page.getByRole("button", { name: "Start workout", exact: true }).click();
	await page.waitForURL("**/workout?id=*");
	id = new URL(page.url()).searchParams.get("id");
	assert.ok(id);
	await page.getByRole("heading", { name: "Workout in progress" }).waitFor();
	assert.equal(await page.getByRole("button", { name: "Finish workout" }).isDisabled(), true);
	await page.locator("#record input[name=name]").fill("Browser test squat");
	await page.locator("#record input[name=weight]").fill("135");
	await page.getByRole("button", { name: "Record set", exact: true }).click();
	await page.waitForURL("**&saved=1&lift=*");
	await page.getByRole("status").filter({ hasText: "Saved" }).waitFor();
	assert.match(await page.locator("body").innerText(), /1×5 @ 135 lb/);
	// Plates live in the recording form, with bar settings and warmups collapsed.
	const plates = page.getByRole("region", { name: "Plates for this set" });
	await plates.locator('[data-load="135"]').waitFor();
	assert.equal(await plates.locator("[data-load]:visible").count(), 1);
	assert.equal(await page.locator("aside").count(), 0);
	await plates.getByText("Recommended warmup", { exact: true }).click();
	await plates.getByLabel("Starting warmup (lb)", { exact: true }).fill("65");
	await plates.locator('[data-load="85"]').waitFor();
	assert.deepEqual(await plates.locator("[data-load]:visible").evaluateAll((loads) => loads.map((load) => Number(load.dataset.load))), [135, 65, 85, 100, 115]);
	await plates.getByText("Recommended warmup", { exact: true }).click();
	await plates.getByLabel("Bar weight", { exact: true }).selectOption("33");
	await plates.getByText("(51 lb / side)", { exact: true }).waitFor();
	await plates.getByLabel("Bar weight", { exact: true }).selectOption("45");
	await page.locator("#record input[name=sets]").fill("3");
	await page.locator("#record input[name=weight]").fill("315");
	await plates.locator('[data-load="315"]').waitFor();
	const plateGap = await plates.locator("[data-load=\"315\"] p._plate").evaluateAll((plates) => plates[1].getBoundingClientRect().left - plates[0].getBoundingClientRect().right);
	assert.ok(plateGap >= 4, `plates are ${plateGap}px apart`);
	await page.getByRole("button", { name: "Record set", exact: true }).click();
	await page.waitForLoadState("networkidle");
	assert.match(await page.locator("body").innerText(), /3×5 @ 315 lb/);
	await page.getByRole("button", { name: "Remove Browser test squat set 2", exact: true }).click();
	await page.waitForLoadState("networkidle");
	await page.locator("#record input[name=sets]").fill("1");
	await page.locator("#record input[name=weight]").fill("185");
	await plates.locator('[data-load="185"]').waitFor();
	assert.equal(await plates.locator("[data-load]:visible").count(), 1);
	await page.getByRole("button", { name: "Record set", exact: true }).click();
	await page.waitForLoadState("networkidle");
	assert.equal(await page.getByRole("button", { name: /Remove Browser test squat set/ }).count(), 2);
	assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
	await page.screenshot({ path: "/tmp/barcalc-workout-mobile.png", fullPage: true });
	await page.setViewportSize({ width: 1280, height: 900 });
	await page.screenshot({ path: "/tmp/barcalc-workout-desktop.png", fullPage: true });
	assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
	await page.setViewportSize({ width: 390, height: 844 });
	await page.reload();
	assert.match(await page.locator("body").innerText(), /1×5 @ 185 lb/);
	await page.getByRole("link", { name: "← Exercise Log" }).click();
	await page.locator(`a[href="/workout?id=${id}"]`).click();
	assert.equal(new URL(page.url()).searchParams.get("id"), id);
	// A stale revision must not duplicate or overwrite recorded sets.
	const stale = await page.evaluate(async () => {
		const data = new FormData(document.querySelector("#record"));
		data.set("revision", "0");
		const response = await fetch(location.href, { method: "POST", body: data });
		return response.text();
	});
	assert.match(stale, /changed in another tab/);
	await page.getByRole("button", { name: "Remove Browser test squat set 2", exact: true }).click();
	await page.waitForLoadState("networkidle");
	assert.equal(await page.getByRole("button", { name: /Remove Browser test squat set/ }).count(), 1);
	await page.locator("#record input[name=name]").fill("Browser test run");
	await page.locator("#record input[name=reps]").fill("");
	await page.locator("#record input[name=weight]").fill("");
	await page.getByText("Cardio / timed activity", { exact: true }).click();
	await page.locator("input[name=durationSec]").fill("600");
	await page.locator("input[name=distanceM]").fill("1000");
	await page.getByRole("button", { name: "Record set", exact: true }).click();
	await page.waitForLoadState("networkidle");
	assert.match(await page.locator("body").innerText(), /1000 m 10:00/);
	// Server validation retains the attempted values and leaves saved sets unchanged.
	const invalid = await page.evaluate(async () => {
		const data = new FormData(document.querySelector("#record"));
		data.set("reps", "-1");
		const response = await fetch(location.href, { method: "POST", body: data });
		return response.text();
	});
	assert.match(invalid, /role="alert"/);
	await page.locator("textarea[name=notes]").fill("Browser flow verified");
	await page.getByRole("button", { name: "Finish workout", exact: true }).click();
	await page.waitForURL("**/?saved=*");
	await page.locator(`#session-${id}`).waitFor();
	assert.match(await page.locator(`#session-${id}`).innerText(), /Browser flow verified/);
	assert.match(await page.locator(`#session-${id}`).innerText(), /1000 m 10:00/);
	await page.locator(`#session-${id}`).click();
	await page.getByRole("dialog").waitFor();
	await page.getByRole("dialog").locator("textarea[name=notes]").fill("Edited browser workout");
	await page.getByRole("button", { name: "Save changes", exact: true }).click();
	await page.waitForLoadState("networkidle");
	assert.match(await page.locator(`#session-${id}`).innerText(), /Edited browser workout/);
	assert.match(await page.locator(`#session-${id}`).innerText(), /1000 m 10:00/);
	// Clean up only this test's completed workout using the existing log endpoint.
	await page.evaluate(async (id) => {
		const data = new FormData(); data.set("intent", "delete"); data.set("id", id);
		await fetch("/", { method: "POST", body: data });
	}, id);
	id = undefined;
	await page.goto(base);
	await page.getByRole("button", { name: "Start workout", exact: true }).click();
	await page.waitForURL("**/workout?id=*");
	id = new URL(page.url()).searchParams.get("id");
	assert.equal(await page.getByLabel("Weight (lb)", { exact: true }).count(), 1);
	const emptyFinish = await page.evaluate(async () => {
		const data = new FormData(document.querySelector("form[data-finish]"));
		return (await fetch(location.href, { method: "POST", body: data })).text();
	});
	assert.match(emptyFinish, /Record at least one set/);
	await page.locator("#record input[name=name]").fill("Browser test pounds");
	await page.locator("#record input[name=weight]").fill("80");
	await page.getByRole("button", { name: "Record set", exact: true }).click();
	await page.waitForLoadState("networkidle");
	assert.match(await page.locator("body").innerText(), /1×5 @ 80 lb/);
	await page.getByRole("button", { name: "Discard workout", exact: true }).click();
	await page.waitForURL((url) => url.pathname === "/");
	id = undefined;
	await page.goto(`${base}/calculator`);
	await page.getByLabel("Work weight (lb)", { exact: true }).waitFor();
	assert.equal(await page.getByRole("radio").count(), 0);
	await page.getByLabel("Bar weight", { exact: true }).selectOption("15");
	await page.getByText("(152.5 lb / side)", { exact: true }).waitFor();
	assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
	assert.deepEqual(errors, []);
	console.log("workout browser check ok: start, record, calculator, resume, stale/invalid input, remove, cardio, finish, history editing, pounds default, optional warmups/bar settings, empty finish, discard, standalone calculator");
} finally {
	if (id) console.error(`Test interrupted; inspect local workout ${id}`);
	await browser.close();
}
